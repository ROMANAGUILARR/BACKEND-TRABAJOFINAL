-- =============================================================
-- V1__init.sql — Esquema inicial de EcoSolido (PostgreSQL / Supabase)
-- Tablas: usuario, incidencia, incidencia_foto, insignia, usuario_insignia
-- =============================================================

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo     VARCHAR(255) NOT NULL,
    apellido_completo   VARCHAR(255) NOT NULL,
    dni                 VARCHAR(255),
    telefono            VARCHAR(255),
    nombre_usuario      VARCHAR(255) NOT NULL,
    contrasena          VARCHAR(255) NOT NULL,
    pregunta_seguridad  VARCHAR(255),
    correo_electronico  VARCHAR(255),
    respuesta_pregunta  VARCHAR(255),
    puntos              INT NOT NULL DEFAULT 0,
    rol                 VARCHAR(20) DEFAULT 'CIUDADANO',
    CONSTRAINT uk_usuario_nombre UNIQUE (nombre_usuario),
    CONSTRAINT chk_usuario_rol CHECK (rol IN ('CIUDADANO','ADMIN'))
);

CREATE TABLE IF NOT EXISTS incidencia (
    id_incidencia   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion     TEXT NOT NULL,
    categoria       VARCHAR(255),
    estado          VARCHAR(20) DEFAULT 'PENDIENTE',
    fecha           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    id_ciudadano    BIGINT,
    titulo          VARCHAR(255),
    latitud         DOUBLE PRECISION,
    longitud        DOUBLE PRECISION,
    direccion_texto VARCHAR(255),
    CONSTRAINT fk_incidencia_usuario FOREIGN KEY (id_ciudadano)
        REFERENCES usuario (id_usuario),
    CONSTRAINT chk_estado CHECK (estado IN ('PENDIENTE','EN_PROCESO','RESUELTO'))
);
CREATE INDEX IF NOT EXISTS idx_incidencia_ciudadano ON incidencia (id_ciudadano);

CREATE TABLE IF NOT EXISTS incidencia_foto (
    id_foto        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incidencia  BIGINT NOT NULL,
    url_foto       VARCHAR(500),
    public_id      VARCHAR(255),
    CONSTRAINT fk_foto_incidencia FOREIGN KEY (id_incidencia)
        REFERENCES incidencia (id_incidencia)
);
CREATE INDEX IF NOT EXISTS idx_foto_incidencia ON incidencia_foto (id_incidencia);

CREATE TABLE IF NOT EXISTS insignia (
    id_insignia             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                  VARCHAR(255) NOT NULL,
    descripcion             VARCHAR(1000) NOT NULL,
    icono                   VARCHAR(255) NOT NULL,
    requisito_incidencias   INT NOT NULL,
    recompensa              VARCHAR(500),
    CONSTRAINT uk_insignia_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS usuario_insignia (
    id_usuario_insignia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario          BIGINT NOT NULL,
    id_insignia         INT NOT NULL,
    fecha_desbloqueo    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_insignia UNIQUE (id_usuario, id_insignia),
    CONSTRAINT fk_ui_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario),
    CONSTRAINT fk_ui_insignia FOREIGN KEY (id_insignia)
        REFERENCES insignia (id_insignia)
);
CREATE INDEX IF NOT EXISTS idx_ui_insignia ON usuario_insignia (id_insignia);
