-- =============================================================
-- V10 — Cuadrillas de atención, evidencias de resolución e historial
--   cuadrilla             equipos de limpieza (con zona/distrito)
--   trabajador            integrantes de cada cuadrilla (uno puede ser jefe)
--   incidencia            + cuadrilla asignada, fecha de asignación y de resolución
--   incidencia_evidencia  fotos del trabajo terminado
--   incidencia_historial  quién cambió qué y cuándo
-- =============================================================

CREATE TABLE IF NOT EXISTS cuadrilla (
    id_cuadrilla    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    zona            VARCHAR(150),
    activa          BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cuadrilla_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS trabajador (
    id_trabajador    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuadrilla     INT NOT NULL,
    nombre_completo  VARCHAR(200) NOT NULL,
    dni              VARCHAR(8),
    telefono         VARCHAR(9),
    es_jefe          BOOLEAN NOT NULL DEFAULT FALSE,
    activo           BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_trabajador_cuadrilla FOREIGN KEY (id_cuadrilla)
        REFERENCES cuadrilla (id_cuadrilla) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_trabajador_cuadrilla ON trabajador (id_cuadrilla);

ALTER TABLE incidencia ADD COLUMN IF NOT EXISTS id_cuadrilla INT;
ALTER TABLE incidencia ADD COLUMN IF NOT EXISTS fecha_asignacion TIMESTAMP;
ALTER TABLE incidencia ADD COLUMN IF NOT EXISTS fecha_resolucion TIMESTAMP;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_incidencia_cuadrilla') THEN
    ALTER TABLE incidencia ADD CONSTRAINT fk_incidencia_cuadrilla
      FOREIGN KEY (id_cuadrilla) REFERENCES cuadrilla (id_cuadrilla) ON DELETE SET NULL;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_incidencia_cuadrilla ON incidencia (id_cuadrilla);

CREATE TABLE IF NOT EXISTS incidencia_evidencia (
    id_evidencia   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incidencia  BIGINT NOT NULL,
    url_foto       VARCHAR(500) NOT NULL,
    public_id      VARCHAR(255),
    fecha          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_evidencia_incidencia FOREIGN KEY (id_incidencia)
        REFERENCES incidencia (id_incidencia) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_evidencia_incidencia ON incidencia_evidencia (id_incidencia);

CREATE TABLE IF NOT EXISTS incidencia_historial (
    id_historial     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incidencia    BIGINT NOT NULL,
    tipo             VARCHAR(20) NOT NULL,
    estado_anterior  VARCHAR(20),
    estado_nuevo     VARCHAR(20),
    detalle          VARCHAR(500),
    realizado_por    VARCHAR(255),
    fecha            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_historial_incidencia FOREIGN KEY (id_incidencia)
        REFERENCES incidencia (id_incidencia) ON DELETE CASCADE,
    CONSTRAINT chk_historial_tipo CHECK (tipo IN ('ESTADO', 'ASIGNACION', 'EVIDENCIA'))
);
CREATE INDEX IF NOT EXISTS idx_historial_incidencia ON incidencia_historial (id_incidencia);

-- Supabase Realtime también para las tablas nuevas (no hace nada fuera de Supabase)
DO $$
DECLARE t TEXT;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    FOREACH t IN ARRAY ARRAY['cuadrilla','trabajador','incidencia_evidencia','incidencia_historial'] LOOP
      IF NOT EXISTS (SELECT 1 FROM pg_publication_tables
                     WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = t) THEN
        EXECUTE format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I', t);
      END IF;
    END LOOP;
  END IF;
END $$;
